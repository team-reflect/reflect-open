//! Writes the TypeScript (`@reflect/types`) and Swift (`TypesShared`) files
//! generated from the wire types. Run `pnpm gen:types`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use reflect_types::commands;
use reflect_types::events::EventName;
use reflect_types::{
    APP_GROUP_KEY, AppError, AssetResolveReply, CaptureAck, CapturePointer, CaptureWireMessage,
    ChromeIntent, ChromeMessage, CoreStartConfig, FileChange, GraphImportProgress,
    INBOX_SPOOL_MAX_BYTES, LinkCaptureEnvelope, QUICK_NOTE_DEFAULTS_FILE, QuickNoteDefaultsFile,
    RecordingLevelEvent, RecordingNativeActionEvent, RecordingSegmentEvent, RecordingStoppedEvent,
    SHARED_ENVELOPE_MAX_BYTES, SHARED_INBOX_DIR, SHARED_SCREENSHOT_MAX_BYTES, TextCaptureEnvelope,
};
use specta::Types;
use specta::datatype::{DataType, Primitive};

const HEADER: &str = "Generated by `pnpm gen:types` from `crates/types`. Do not edit.";

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    // The command table registers every argument and result type; specta adds
    // the types they reference. The rest are event payloads and names, the
    // JSON that crosses the C interface, the capture inbox files, and the Swift
    // shell's plugin events and chrome protocol.
    let types = commands::register(
        Types::default()
            .register::<AppError>()
            .register::<EventName>()
            .register::<FileChange>()
            .register::<GraphImportProgress>()
            .register::<CoreStartConfig>()
            .register::<AssetResolveReply>()
            .register::<LinkCaptureEnvelope>()
            .register::<TextCaptureEnvelope>()
            .register::<CaptureWireMessage>()
            .register::<CaptureAck>()
            .register::<CapturePointer>()
            .register::<QuickNoteDefaultsFile>()
            .register::<RecordingLevelEvent>()
            .register::<RecordingSegmentEvent>()
            .register::<RecordingStoppedEvent>()
            .register::<RecordingNativeActionEvent>()
            .register::<ChromeMessage>()
            .register::<ChromeIntent>(),
    );
    // The manifest maps each command to its inline arguments and result, which
    // specta-swift cannot render, so only TypeScript gets it.
    let ts_types = types.clone().register::<commands::Commands>();

    write(
        &root.join("packages/types/src/wire.gen.ts"),
        &name_shell_commands(&typescript(&ts_types)),
    );
    write(
        &root.join("apple/Sources/TypesShared/Wire.gen.swift"),
        &swift(&types),
    );
}

/// TypeScript types.
fn typescript(types: &Types) -> String {
    // JavaScript numbers hold every integer below 2^53, which covers every
    // 64-bit value the app sends. The remapper turns 64-bit integers into
    // 32-bit ones, which TypeScript renders as `number`. Swift keeps `UInt64`.
    // Floats render as `number | null` (serde writes NaN as `null`); the app
    // never sends NaN, so they become `number`. Free-form JSON becomes
    // `unknown`: the frontend validates what it reads and sends plain objects.
    let number = DataType::Reference(specta_typescript::define("number"));
    let json = <serde_json::Value as specta::Type>::definition(&mut Types::default());
    let remapper = specta_util::Remapper::new()
        .dangerous_bigints_as_number()
        .rule(Primitive::f32.into(), number.clone())
        .rule(Primitive::f64.into(), number)
        .rule(
            json,
            DataType::Reference(specta_typescript::define("unknown")),
        );
    let out = specta_typescript::Typescript::default()
        .header(format!("// {HEADER}"))
        .export(&remapper.remap_types(types.clone()), specta_serde::Format)
        .expect("typescript export");
    add_undefined(&out)
}

/// Renames each Swift shell command in `Commands` from its identifier to its
/// name (`recording_start` to `"plugin:recording|start_recording"`).
// TODO: put `#[serde(rename)]` on the fields instead once specta reads it on
// a type that does not derive serde.
fn name_shell_commands(ts: &str) -> String {
    let mut out = ts.to_owned();
    for (ident, name) in commands::SHELL_COMMANDS {
        let field = format!("\n\t{ident}: {{\n");
        assert!(out.contains(&field), "`Commands` has no field {ident}");
        out = out.replace(&field, &format!("\n\t{name:?}: {{\n"));
    }
    out
}

/// Serde omits a `None` field, but TypeScript code often builds the object
/// with `field: undefined`. With `exactOptionalPropertyTypes`, an optional
/// property must say `| undefined` to accept that.
// TODO: remove once specta-typescript can emit `| undefined` for optional
// properties; this needs an upstream pull request.
fn add_undefined(ts: &str) -> String {
    let mut out = String::with_capacity(ts.len());
    for line in ts.split_inclusive('\n') {
        // A doc comment can quote `?: ` too.
        if line.trim_start().starts_with(['/', '*']) {
            out.push_str(line);
            continue;
        }
        let mut parts = line.split("?: ");
        out.push_str(parts.next().unwrap_or_default());
        for part in parts {
            // The property type runs to the end of the property.
            let end = [",", ";", " }", "\n"]
                .iter()
                .filter_map(|stop| part.find(stop))
                .min()
                .unwrap_or(part.len());
            let (ty, rest) = part.split_at(end);
            write!(out, "?: {ty} | undefined{rest}").unwrap();
        }
    }
    out
}

/// `Codable` types.
fn swift(types: &Types) -> String {
    let out = specta_swift::Swift::default()
        .header(format!("// {HEADER}\n// swift-format-ignore-file"))
        .add_protocol("Equatable")
        .export(types, specta_serde::Format)
        .expect("swift export");
    // A unit enum lists its cases, as the shell's tab bar needs.
    let out = out.replace(
        ": String, Codable, Sendable, Equatable {",
        ": String, Codable, Sendable, Equatable, CaseIterable {",
    );
    drop_value(&rename_cases(&add_public_inits(&out))) + &capture_constants() + &shell_commands()
}

/// The command table's Swift shell commands, which the codegen cannot render
/// as a `Commands` struct for Swift.
fn shell_commands() -> String {
    let mut out = String::from(
        "\n/// The name of every command the Swift shell answers.\npublic enum ShellCommandName: String, CaseIterable, Sendable {\n",
    );
    for (ident, name) in commands::SHELL_COMMANDS {
        let mut case = String::new();
        for (i, word) in ident.split('_').enumerate() {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) if i > 0 => case.extend(first.to_uppercase().chain(chars)),
                _ => case.push_str(word),
            }
        }
        writeln!(out, "    case {case} = {name:?}").unwrap();
    }
    out.push_str("}\n");
    out
}

/// The capture names and limits the Swift producers share with Rust.
fn capture_constants() -> String {
    format!(
        "
/// The capture inbox names and limits.
public enum CaptureConstants {{
    /// The Info.plist key that names the flavor's App Group.
    public static let appGroupKey = {APP_GROUP_KEY:?}
    /// The spool directory inside the App Group container.
    public static let sharedInboxDir = {SHARED_INBOX_DIR:?}
    /// The largest envelope the relay copies out of the App Group container.
    public static let sharedEnvelopeMaxBytes = {SHARED_ENVELOPE_MAX_BYTES}
    /// The largest screenshot the relay copies out of the App Group container.
    public static let sharedScreenshotMaxBytes = {SHARED_SCREENSHOT_MAX_BYTES}
    /// The largest envelope the iOS producers spool.
    public static let inboxSpoolMaxBytes = {INBOX_SPOOL_MAX_BYTES}
    /// The quick note defaults file inside the App Group container.
    public static let quickNoteDefaultsFile = {QUICK_NOTE_DEFAULTS_FILE:?}
}}
"
    )
}

/// specta-swift gives the payload struct of an enum variant (`AppErrorIoData`)
/// no `public init`, so another module cannot build the enum. Adds a
/// memberwise one to every struct that holds only `public let` properties.
fn add_public_inits(swift: &str) -> String {
    let mut out = String::new();
    let mut lines = swift.lines();
    while let Some(line) = lines.next() {
        out.push_str(line);
        out.push('\n');
        if !(line.starts_with("public struct ") && line.ends_with('{')) {
            continue;
        }
        let mut body = Vec::new();
        for inner in lines.by_ref() {
            if inner == "}" {
                break;
            }
            body.push(inner);
        }
        let properties: Option<Vec<(&str, &str)>> = body
            .iter()
            .map(|inner| inner.trim().strip_prefix("public let ")?.split_once(": "))
            .collect();
        for inner in &body {
            out.push_str(inner);
            out.push('\n');
        }
        if let Some(properties) = properties.filter(|p| !p.is_empty()) {
            let parameters: Vec<String> = properties
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect();
            writeln!(out, "\n    public init({}) {{", parameters.join(", ")).unwrap();
            for (name, _) in &properties {
                writeln!(out, "        self.{name} = {name}").unwrap();
            }
            out.push_str("    }\n");
        }
        out.push_str("}\n");
    }
    out
}

/// specta-swift names a case after its serde name (`case index:changed`),
/// which is not a Swift identifier. Renames such a case after the words of
/// its name (`case indexChanged`); the raw value keeps the wire name.
// TODO: remove once specta-swift names cases after the Rust variant; this
// needs an upstream pull request.
fn rename_cases(swift: &str) -> String {
    let mut out = String::new();
    for line in swift.split_inclusive('\n') {
        let name = line
            .trim_start()
            .strip_prefix("case ")
            .and_then(|rest| rest.split_once(" = \""))
            .map(|(name, _)| name)
            .filter(|name| !name.chars().all(char::is_alphanumeric));
        let Some(name) = name else {
            out.push_str(line);
            continue;
        };
        let mut ident = String::new();
        for (i, word) in name.split(|c: char| !c.is_alphanumeric()).enumerate() {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) if i > 0 => ident.extend(first.to_uppercase().chain(chars)),
                _ => ident.push_str(word),
            }
        }
        out.push_str(&line.replacen(name, &ident, 1));
    }
    out
}

/// Removes the generated `Value` enum, which does not compile:
/// `apple/Sources/TypesShared/Value.swift` defines it by hand.
// TODO: remove once specta-swift renders `serde_json::Value`; this needs an
// upstream pull request.
fn drop_value(swift: &str) -> String {
    let Some(start) = swift.find("public enum Value: ") else {
        return swift.to_owned();
    };
    let end = start + swift[start..].find("\n}\n").expect("end of `Value`") + 3;
    format!("{}{}", &swift[..start], &swift[end..])
}

fn write(path: &PathBuf, contents: &str) {
    std::fs::create_dir_all(path.parent().expect("parent")).expect("create dir");
    std::fs::write(path, contents).expect("write");
}
