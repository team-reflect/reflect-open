//! Writes the TypeScript (`@reflect/types`), Swift (`TypesShared`), and
//! fixture files generated from the wire types. Run `pnpm gen:types`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use reflect_types::{AppError, ChangeKind, FileChange, FileMeta, events};
use serde::Serialize;
use specta::Types;
use specta::datatype::{DataType, Primitive};

const HEADER: &str = "Generated by `pnpm gen:types` from `crates/types`. Do not edit.";

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let types = Types::default()
        .register::<AppError>()
        .register::<FileChange>()
        .register::<FileMeta>();

    write(
        &root.join("packages/types/src/wire.gen.ts"),
        &typescript(&types),
    );
    write(
        &root.join("apple/Sources/TypesShared/Wire.gen.swift"),
        &swift(&types),
    );
    write_fixtures(&root.join("fixtures/wire"));
}

/// zod schemas and their inferred types, then the event names.
fn typescript(types: &Types) -> String {
    // JavaScript numbers hold every integer below 2^53, which covers every
    // 64-bit value the app sends, so 64-bit integers become plain numbers.
    let mut remapper = specta_util::Remapper::new();
    for primitive in [
        Primitive::u64,
        Primitive::i64,
        Primitive::usize,
        Primitive::isize,
    ] {
        remapper = remapper.rule(
            DataType::Primitive(primitive),
            DataType::Reference(specta_zod::define("z.number()")),
        );
    }
    let out = specta_zod::Zod::default()
        .header(format!("// {HEADER}"))
        .export(&remapper.remap_types(types.clone()), specta_serde::Format)
        .expect("zod export");
    // specta-zod types a custom zod expression as `unknown` in the inferred
    // TypeScript type. The only custom expression is the `z.number()` above,
    // so each one pairs with exactly one `: unknown`.
    assert_eq!(
        out.matches(": unknown").count(),
        out.matches("z.number()").count(),
        "a wire type renders as `unknown` in TypeScript; map it in `typescript()`"
    );
    let mut out = add_undefined(&out.replace(": unknown", ": number"));
    out.push('\n');
    for (name, value) in events::ALL {
        writeln!(out, "export const {name} = '{value}'").unwrap();
    }
    out
}

/// zod's `.optional()` infers `T | undefined`, so with
/// `exactOptionalPropertyTypes` an optional property must accept `undefined`
/// to match its schema.
fn add_undefined(ts: &str) -> String {
    let mut out = String::new();
    for line in ts.lines() {
        match line.strip_suffix(',') {
            Some(field) if field.trim_start().split_once("?: ").is_some() => {
                writeln!(out, "{field} | undefined,").unwrap();
            }
            _ => writeln!(out, "{line}").unwrap(),
        }
    }
    out
}

/// `Codable` types, then the event names.
fn swift(types: &Types) -> String {
    let out = specta_swift::Swift::default()
        .header(format!("// {HEADER}"))
        .add_protocol("Equatable")
        .export(types, specta_serde::Format)
        .expect("swift export");
    let mut out = add_public_inits(&out);
    out.push_str("\n/// The names of the events the native side broadcasts to the page.\npublic enum WireEvent {\n");
    for (name, value) in events::ALL {
        writeln!(
            out,
            "  public static let {} = \"{value}\"",
            lower_camel(name)
        )
        .unwrap();
    }
    out.push_str("}\n");
    out
}

/// specta-swift gives the payload struct of an enum variant (`AppErrorIoData`)
/// no `public init`, so another module cannot build the enum. Adds a
/// memberwise one to every struct that holds only `public let` properties.
fn add_public_inits(swift: &str) -> String {
    let mut out = String::new();
    let mut lines = swift.lines();
    while let Some(line) = lines.next() {
        out.push_str(line);
        out.push('\n');
        if !(line.starts_with("public struct ") && line.ends_with('{')) {
            continue;
        }
        let mut body = Vec::new();
        for inner in lines.by_ref() {
            if inner == "}" {
                break;
            }
            body.push(inner);
        }
        let properties: Option<Vec<(&str, &str)>> = body
            .iter()
            .map(|inner| inner.trim().strip_prefix("public let ")?.split_once(": "))
            .collect();
        for inner in &body {
            out.push_str(inner);
            out.push('\n');
        }
        if let Some(properties) = properties.filter(|p| !p.is_empty()) {
            let parameters: Vec<String> = properties
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect();
            writeln!(out, "\n    public init({}) {{", parameters.join(", ")).unwrap();
            for (name, _) in &properties {
                writeln!(out, "        self.{name} = {name}").unwrap();
            }
            out.push_str("    }\n");
        }
        out.push_str("}\n");
    }
    out
}

/// One JSON file per type: an array of samples as serde writes them. The
/// TypeScript and Swift tests decode every sample with the generated types.
fn write_fixtures(dir: &Path) {
    fixture(
        dir,
        "AppError",
        &[
            AppError::Io {
                message: "disk full".into(),
                git_code: Some(-14),
            },
            AppError::not_found("notes/a.md"),
            AppError::traversal("../etc/passwd"),
            AppError::no_graph(),
            AppError::parse("bad frontmatter"),
            AppError::Auth {
                message: "token expired".into(),
            },
            AppError::Network {
                message: "offline".into(),
            },
            AppError::Unknown {
                message: "boom".into(),
            },
        ],
    );
    fixture(dir, "ChangeKind", &[ChangeKind::Upsert, ChangeKind::Remove]);
    fixture(
        dir,
        "FileChange",
        &[
            FileChange::upsert("notes/a.md", Some(1_763_000_000_000)),
            FileChange::upsert("notes/b.md", None),
            FileChange::remove("notes/a.md"),
        ],
    );
    fixture(
        dir,
        "FileMeta",
        &[
            FileMeta {
                path: "notes/a.md".into(),
                size: 3,
                modified_ms: 1_763_000_000_000,
                placeholder: false,
            },
            FileMeta {
                path: "notes/b.md".into(),
                size: 0,
                modified_ms: 9,
                placeholder: true,
            },
        ],
    );
}

fn fixture<T: Serialize>(dir: &Path, name: &str, samples: &[T]) {
    let json = serde_json::to_string_pretty(samples).expect("serialize fixture");
    write(&dir.join(format!("{name}.json")), &format!("{json}\n"));
}

fn write(path: &PathBuf, contents: &str) {
    std::fs::create_dir_all(path.parent().expect("parent")).expect("create dir");
    std::fs::write(path, contents).expect("write");
}

/// `INDEX_CHANGED` to `indexChanged`.
fn lower_camel(name: &str) -> String {
    let mut out = String::new();
    for (i, word) in name.split('_').enumerate() {
        let lower = word.to_lowercase();
        if i == 0 {
            out.push_str(&lower);
        } else {
            let mut chars = lower.chars();
            if let Some(first) = chars.next() {
                out.extend(first.to_uppercase());
                out.push_str(chars.as_str());
            }
        }
    }
    out
}
