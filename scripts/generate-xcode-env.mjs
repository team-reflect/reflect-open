// Generates a gitignored `.xcode.env.local` for the Xcode project in
// apps/ios. The Xcode build phases source it:
// Xcode launched from the Dock runs script phases with the minimal launchd
// PATH, so they cannot find node or cargo on their own. The file records the
// node toolchain of the environment that ran `pnpm install`, the PATH entries
// mise manages for this repository (its `cargo` wrapper, which runs cargo
// through mbx, comes first), and the fixed install location of rustup. Runs
// from scripts' postinstall, where PATH is correct by construction. Same idea
// as React Native's `.xcode.env.local`.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'

if (process.platform === 'darwin') {
  const rootDir = join(import.meta.dirname, '..')
  const target = join(rootDir, 'apps', 'ios', '.xcode.env.local')

  const nodeBinary = process.execPath
  const nodeDir = dirname(nodeBinary)
  const miseDirs = getMisePaths(rootDir)

  const content = `# Generated by scripts/generate-xcode-env.mjs (scripts postinstall).
# Records the node toolchain of the environment that ran \`pnpm install\`, so
# the Xcode build phases (which run with the minimal launchd PATH) use the
# same one, and adds mise's tools and rustup's cargo. Regenerated on every
# install; do not edit by hand.
export NODE_BINARY="${nodeBinary}"
export PATH="${[nodeDir, ...miseDirs].join(':')}:$PATH:$HOME/.cargo/bin"
`

  writeFileSync(target, content)
  console.log(`generate-xcode-env: wrote ${target} (node ${process.version})`)
}

/**
 * The PATH entries that mise manages for the repository, in order. Empty when
 * mise is not installed or does not trust the repository's `mise.toml`.
 */
function getMisePaths(cwd) {
  try {
    const output = execFileSync('mise', ['env', '--paths'], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
    return output.split('\n').filter(Boolean)
  } catch {
    return []
  }
}
