// Generates the Content-Security-Policy of the Swift iOS shell from the one
// in apps/tauri/tauri.conf.json: the same policy, with the
// `reflect-app:` scheme in place of the Tauri IPC sources.
//
//   pnpm gen:ios-csp

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT_DIR = join(import.meta.dirname, '..')
const TAURI_CONFIG_PATH = join(ROOT_DIR, 'apps', 'tauri', 'tauri.conf.json')
const OUTPUT_PATH = join(
  ROOT_DIR,
  'apple',
  'Sources',
  'WebHostKit',
  'ContentSecurityPolicy.gen.swift',
)
const TAURI_IPC_SOURCES = ['ipc:', 'http://ipc.localhost']
const SHELL_IPC_SOURCE = 'reflect-app:'
const LINE_LENGTH = 100

const config = JSON.parse(readFileSync(TAURI_CONFIG_PATH, 'utf8')) as {
  app: { security: { csp: string } }
}

const directives = config.app.security.csp.split(';').map((directive) => {
  const tokens = directive.trim().split(/\s+/)
  const kept = tokens.filter((token) => !TAURI_IPC_SOURCES.includes(token))
  if (kept.length === tokens.length) {
    return kept
  }
  // The IPC source goes right after `'self'`, where the Tauri ones were.
  const index = tokens.findIndex((token) => TAURI_IPC_SOURCES.includes(token))
  return [...kept.slice(0, index), SHELL_IPC_SOURCE, ...kept.slice(index)]
})

// The layout `swift format` gives an array literal: one line when it fits,
// else one element per line.
const rows = directives.map((tokens) => {
  const elements = tokens.map((token) => JSON.stringify(token))
  const line = `    [${elements.join(', ')}],`
  if (line.length <= LINE_LENGTH) {
    return line
  }
  return ['    [', ...elements.map((element) => `      ${element},`), '    ],'].join('\n')
})

writeFileSync(
  OUTPUT_PATH,
  `// Generated by \`pnpm gen:ios-csp\`.

/// The Content-Security-Policy of the web app's HTML.
enum ContentSecurityPolicy {
  private static let directives: [[String]] = [
${rows.join('\n')}
  ]

  /// The value of the \`Content-Security-Policy\` header.
  static let header = directives.map { $0.joined(separator: " ") }.joined(separator: "; ")
}
`,
)
