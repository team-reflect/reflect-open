// Generates src-tauri/.xcode.env.local (gitignored), recording the node
// toolchain of the environment that ran `pnpm install`. The Xcode build
// phases (xcode-scripts/*.sh) source it: Xcode launched from the Dock runs
// script phases with the minimal launchd PATH, so they cannot find node on
// their own. Runs from apps/desktop's postinstall, where PATH is correct by
// construction. Same idea as React Native's `.xcode.env.local`.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'

if (process.platform === 'darwin') {
  const scriptDir = import.meta.dirname
  const target = join(scriptDir, '..', '.xcode.env.local')

  const nodeBinary = process.execPath
  const nodeDir = dirname(nodeBinary)

  const content = `# Generated by xcode-scripts/generate-xcode-env.mjs (apps/desktop postinstall).
# Records the node toolchain of the environment that ran \`pnpm install\`, so
# the Xcode build phases (which run with the minimal launchd PATH) use the
# same one. Regenerated on every install; do not edit by hand.
export NODE_BINARY="${nodeBinary}"
export PATH="${nodeDir}:$PATH"
`

  writeFileSync(target, content)
  console.log(`generate-xcode-env: wrote ${target} (node ${process.version})`)
}
